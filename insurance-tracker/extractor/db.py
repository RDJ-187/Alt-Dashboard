"""PostgreSQL storage (psycopg 3). Connection comes from DATABASE_URL (environment or the project .env).

Tables
  policies          one row per unique PDF (by SHA-256) with every extracted field, properly typed
  field_checks      per-field audit trail: rules value, LLM value, verdict
  issues            validation warnings / errors per policy
  duplicates        byte-identical PDF copies that were skipped
  import_log        dashboard: every policy imported through the upload page
View
  vehicles          latest policy per chassis number (what the tracker shows)

Re-extraction only upserts policies and their checks/issues; dashboard tables are never touched.
"""
from __future__ import annotations

import json
import os
import re
from datetime import date, datetime
from decimal import Decimal
from pathlib import Path

import psycopg
from psycopg.rows import dict_row
from psycopg.types.json import Jsonb

PROJECT = Path(__file__).resolve().parents[1]

POLICY_COLUMNS = [
    "sha256", "file", "source_folder", "pages", "status", "llm_agreement", "review_reasons",
    "insurer", "product", "policy_type", "policy_no", "legacy_policy_no", "issue_date",
    "od_start", "od_end", "tp_start", "tp_end", "tp_policy_no", "tp_insurer", "next_renewal_date",
    "registration_no", "registration_no_filename", "registration_date", "chassis_no", "engine_no",
    "make", "oem", "model", "vehicle_class", "body_type", "carrier_type", "vehicle_usage", "fuel_type",
    "year_of_manufacture", "cubic_capacity",
    "insured_name", "city", "city_clean", "state", "hypothecation", "financier",
    "idv", "od_premium", "od_base_premium", "tp_premium", "total_premium", "ncb_percent",
    "compulsory_deductible", "fire_total_loss_excess", "addons",
    "fire_covered", "fire_note", "fire_exclusion_text", "chassis_damage_covered", "chassis_damage_causes",
    "previous_policy_no", "previous_insurer", "previous_policy_type", "previous_policy_start", "previous_policy_end",
    "extracted_at",
]
DATE_COLS = {"issue_date", "od_start", "od_end", "tp_start", "tp_end", "next_renewal_date", "registration_date",
             "previous_policy_start", "previous_policy_end"}
NUM_COLS = {"idv", "od_premium", "od_base_premium", "tp_premium", "total_premium", "ncb_percent",
            "compulsory_deductible", "fire_total_loss_excess", "llm_agreement"}
INT_COLS = {"pages", "year_of_manufacture"}
JSON_COLS = {"addons", "chassis_damage_causes", "review_reasons"}
TS_COLS = {"extracted_at"}


def _sqltype(c: str) -> str:
    if c == "sha256":
        return "TEXT NOT NULL UNIQUE"
    if c in DATE_COLS:
        return "DATE"
    if c in NUM_COLS:
        return "NUMERIC(14,3)"
    if c in INT_COLS:
        return "INTEGER"
    if c in JSON_COLS:
        return "JSONB"
    if c in TS_COLS:
        return "TIMESTAMPTZ"
    return "TEXT"


SCHEMA = f"""
CREATE TABLE IF NOT EXISTS policies (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  {", ".join(f'{c} {_sqltype(c)}' for c in POLICY_COLUMNS)}
);
CREATE INDEX IF NOT EXISTS ix_pol_chassis ON policies (chassis_no);
CREATE INDEX IF NOT EXISTS ix_pol_od_end ON policies (od_end);
CREATE INDEX IF NOT EXISTS ix_pol_reg ON policies (registration_no);

CREATE TABLE IF NOT EXISTS field_checks (
  policy_id BIGINT NOT NULL REFERENCES policies(id) ON DELETE CASCADE,
  field TEXT NOT NULL, rules_value TEXT, llm_value TEXT, verdict TEXT NOT NULL,
  llm_ungrounded BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS ix_fc_policy ON field_checks (policy_id);

CREATE TABLE IF NOT EXISTS issues (
  policy_id BIGINT NOT NULL REFERENCES policies(id) ON DELETE CASCADE,
  severity TEXT NOT NULL, field TEXT, message TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_issues_policy ON issues (policy_id);

CREATE TABLE IF NOT EXISTS duplicates (
  file TEXT PRIMARY KEY, sha256 TEXT NOT NULL, duplicate_of TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS import_log (
  id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  batch TEXT NOT NULL, file_name TEXT NOT NULL, sha256 TEXT, outcome TEXT NOT NULL,
  policy_id BIGINT REFERENCES policies(id) ON DELETE SET NULL, chassis_no TEXT, od_end DATE,
  imported_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE OR REPLACE VIEW vehicles AS
  SELECT DISTINCT ON (chassis_no) *
  FROM policies
  ORDER BY chassis_no, od_end DESC NULLS LAST, id DESC;
"""


def database_url() -> str:
    """DATABASE_URL from the environment, else from the project's .env file."""
    url = os.environ.get("DATABASE_URL")
    if not url:
        env = PROJECT / ".env"
        if env.exists():
            for line in env.read_text(encoding="utf-8").splitlines():
                if line.strip().startswith("DATABASE_URL="):
                    url = line.split("=", 1)[1].strip()
    if not url:
        raise RuntimeError("DATABASE_URL is not set (environment or insurance-tracker/.env)")
    return url


def safe_url(url: str | None = None) -> str:
    return re.sub(r"://([^:/]+):[^@]+@", r"://\1:***@", url or database_url())


def connect(*, autocommit: bool = False, init: bool = True) -> psycopg.Connection:
    con = psycopg.connect(database_url(), row_factory=dict_row, autocommit=autocommit, connect_timeout=10)
    if init:
        with con.transaction():
            con.execute(SCHEMA)
    return con


def to_db(col: str, v):
    """Convert an extracted value (python object or legacy SQLite text) to the column's type."""
    if v is None or v == "":
        return None
    if col in DATE_COLS:
        return v if isinstance(v, date) and not isinstance(v, datetime) else date.fromisoformat(str(v)[:10])
    if col in NUM_COLS:
        return Decimal(str(v).replace(",", ""))
    if col in INT_COLS:
        return int(float(v))
    if col in JSON_COLS:
        return Jsonb(json.loads(v) if isinstance(v, str) else v)
    if col in TS_COLS:
        return v if isinstance(v, datetime) else datetime.fromisoformat(str(v))
    return str(v)


def _text(v):
    if v is None:
        return None
    if isinstance(v, (list, dict)):
        return json.dumps(v, ensure_ascii=False)
    if isinstance(v, (date, datetime)):
        return v.isoformat()
    return str(v)


UPSERT = (f"INSERT INTO policies ({', '.join(POLICY_COLUMNS)}) VALUES ({', '.join(['%s'] * len(POLICY_COLUMNS))}) "
          f"ON CONFLICT (sha256) DO UPDATE SET "
          + ", ".join(f"{c} = EXCLUDED.{c}" for c in POLICY_COLUMNS if c != "sha256")
          + " RETURNING id")


def save(con: psycopg.Connection, rec: dict, rc: dict) -> int:
    f = dict(rec["fields"])
    row = {**f, "sha256": rec["sha256"], "file": rec["file"], "source_folder": rec["source_folder"],
           "pages": rec.get("pages"), "status": rc["status"], "llm_agreement": rc["llm_agreement"],
           "review_reasons": rc["review_reasons"], "extracted_at": datetime.now().astimezone()}
    pid = con.execute(UPSERT, [to_db(c, row.get(c)) for c in POLICY_COLUMNS]).fetchone()["id"]
    con.execute("DELETE FROM field_checks WHERE policy_id = %s", (pid,))
    con.execute("DELETE FROM issues WHERE policy_id = %s", (pid,))
    with con.cursor() as cur:
        cur.executemany("INSERT INTO field_checks VALUES (%s, %s, %s, %s, %s, %s)",
                        [(pid, c["field"], _text(c["rules"]), _text(c["llm"]), c["verdict"], bool(c.get("llm_ungrounded", False)))
                         for c in rc["checks"]])
        cur.executemany("INSERT INTO issues VALUES (%s, %s, %s, %s)",
                        [(pid, i["severity"], i["field"], i["message"]) for i in rec["issues"]])
    return pid


def save_duplicate(con: psycopg.Connection, sha: str, file: str, duplicate_of: str) -> None:
    con.execute("INSERT INTO duplicates (file, sha256, duplicate_of) VALUES (%s, %s, %s) "
                "ON CONFLICT (file) DO UPDATE SET sha256 = EXCLUDED.sha256, duplicate_of = EXCLUDED.duplicate_of",
                (file, sha, duplicate_of))
